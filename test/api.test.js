import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';
import { once } from 'node:events';
import pg from 'pg';
import { createApp } from '../src/app.js';
import { hashPassword } from '../src/password.js';

test('API: cadastro cliente sem SMS, sessão persistente, agenda, reserva concorrente, cancelamento e histórico', async t => {
  const schema = `teste_${randomBytes(8).toString('hex')}`;
  const owner = new pg.Client({ connectionString: process.env.DATABASE_URL });
  await owner.connect();
  await owner.query(`CREATE SCHEMA "${schema}"`);
  const db = new pg.Pool({ connectionString: process.env.DATABASE_URL, options: `-c search_path=${schema}` });
  const servers = [];
  t.after(async () => {
    for (const server of servers) await new Promise(resolve => server.close(resolve));
    await db.end();
    assert.match(schema, /^teste_[a-f0-9]{16}$/);
    await owner.query(`DROP SCHEMA "${schema}" CASCADE`);
    await owner.end();
  });
  for (const file of ['001_estrutura.sql','002_acesso.sql','003_conflitos.sql','004_agendamentos.sql','005_complementos.sql']) await db.query(await readFile(new URL('../database/'+file,import.meta.url),'utf8'));
  const secret = randomBytes(32).toString('hex');
  const boot = async (options={}) => {
    const server = createApp(db, secret, options).listen(0,'127.0.0.1'); servers.push(server);
    await once(server,'listening');
    return `http://127.0.0.1:${server.address().port}`;
  };
  let base = await boot({ frontendOrigin:'http://127.0.0.1:5173' });
  const cors=await fetch(base+'/api/login',{method:'OPTIONS',headers:{Origin:'http://127.0.0.1:5173'}});
  assert.equal(cors.status,204); assert.equal(cors.headers.get('access-control-allow-origin'),'http://127.0.0.1:5173');
  const badCors=await fetch(base+'/api/login',{headers:{Origin:'http://outro.invalid'}});
  assert.equal(badCors.headers.get('access-control-allow-origin'),null); await badCors.text();
  let cookie = '';
  let csrf = '';
  const call = async (path, body) => {
    const response = await fetch(base+'/api'+path, { method: body ? 'POST':'GET', redirect:'manual',
      headers:{Cookie:cookie,'Content-Type':'application/json','X-CSRF-Token':csrf},body:body?JSON.stringify(body):undefined });
    const set = response.headers.get('set-cookie'); if(set) cookie=set.split(';')[0];
    const data = await response.json(); if(data.csrf) csrf=data.csrf;
    return { status:response.status,data };
  };
  assert.equal((await call('/unidades')).status,401);
  assert.equal((await call('/cliente/agendamentos')).status,401);
  assert.equal((await call('/login')).status,200);
  assert.equal((await call('/cadastro',{nome:'Cliente teste',telefone:'71911110000',senha:'curta'})).status,400);
  assert.equal((await call('/cadastro',{nome:'Cliente teste',telefone:'71911110000',senha:'SenhaCliente@2026',perfil:'GESTOR',ativo:false,google_sub:'fraude'})).status,201);
  const registered = (await db.query('SELECT perfil,ativo,google_sub,senha_hash FROM usuario WHERE telefone=$1',['71911110000'])).rows[0];
  assert.equal(registered.perfil,'CLIENTE'); assert.equal(registered.ativo,true); assert.equal(registered.google_sub,null);
  assert.notEqual(registered.senha_hash,'SenhaCliente@2026');
  assert.equal((await db.query('SELECT 1 FROM verificacao_telefone')).rowCount,0);
  assert.equal((await call('/cadastro',{nome:'Duplicado',telefone:'71911110000',senha:'SenhaCliente@2026'})).status,409);
  assert.equal((await call('/cadastro/confirmar',{telefone:'71911110000',codigo:'000000'})).status,404);
  assert.equal((await call('/login',{telefone:'71911110000',senha:'SenhaCliente@2026'})).status,200);
  assert.equal((await call('/sessao')).data.usuario.perfil,'CLIENTE');
  assert.equal((await call('/unidades')).status,403);
  const customerPage = await fetch(base+'/cliente/agendamentos',{headers:{Cookie:cookie}});
  assert.equal(customerPage.status,200); assert.match(await customerPage.text(),/Área do cliente/);
  const customerAccount = await fetch(base+'/conta',{headers:{Cookie:cookie}});
  assert.match(await customerAccount.text(),/href="\/cliente\/agendamentos"/);
  const root = await fetch(base+'/',{headers:{Cookie:cookie},redirect:'manual'});
  assert.equal(root.headers.get('location'),'/cliente/agendamentos'); await root.text();
  const htmlLogin = await fetch(base+'/login',{method:'POST',headers:{Cookie:cookie,'Content-Type':'application/x-www-form-urlencoded'},body:new URLSearchParams({_csrf:csrf,telefone:'71911110000',senha:'SenhaCliente@2026'}),redirect:'manual'});
  assert.equal(htmlLogin.status,303); assert.equal(htmlLogin.headers.get('location'),'/cliente/agendamentos');
  cookie=htmlLogin.headers.get('set-cookie').split(';')[0]; await htmlLogin.text(); await call('/sessao');
  const {rows:[unit]}=await db.query("INSERT INTO unidade(nome,endereco) VALUES ('Teste','Rua teste') RETURNING id");
  const {rows:[staff]}=await db.query("INSERT INTO profissional(nome) VALUES ('Profissional') RETURNING id");
  const {rows:[service]}=await db.query("INSERT INTO servico(nome) VALUES ('Corte') RETURNING id");
  const {rows:[link]}=await db.query('INSERT INTO vinculo_profissional_unidade(profissional_id,unidade_id) VALUES ($1,$2) RETURNING id',[staff.id,unit.id]);
  await db.query('INSERT INTO profissional_servico VALUES ($1,$2)',[staff.id,service.id]);
  await db.query('INSERT INTO oferta_servico(unidade_id,servico_id,preco,duracao_minutos) VALUES ($1,$2,35.50,30)',[unit.id,service.id]);
  await db.query("INSERT INTO turno_trabalho(vinculo_id,dia_semana,hora_inicio,hora_fim) SELECT $1,d,'09:00','18:00' FROM generate_series(1,7) d",[link.id]);
  const {rows:[future]}=await db.query("SELECT to_char((now() AT TIME ZONE 'America/Bahia')::date+7,'YYYY-MM-DD') AS dia");
  const booking={unidade:unit.id,servicos:[service.id],data:future.dia,hora:'10:00'};
  const catalog = await call('/cliente/servicos');
  assert.equal(catalog.status,200,JSON.stringify(catalog.data));
  assert.equal(catalog.data.servicos.length,1);
  assert.equal((await call(`/cliente/unidades?servicos=${service.id}`)).data.unidades.length,1);
  const slots=await call(`/cliente/disponibilidade?unidade=${unit.id}&servicos=${service.id}&data=${future.dia}`);
  assert.equal(slots.status,200);
  assert.ok(slots.data.horarios.some(s=>s.hora==='10:00'));
  assert.equal((await call('/cliente/resumo',booking)).data.valorTotal,'35.50');
  const results=await Promise.all([call('/cliente/agendamentos',booking),call('/cliente/agendamentos',booking)]);
  assert.deepEqual(results.map(r=>r.status).sort(),[201,409]);
  const appointment=results.find(r=>r.status===201).data.agendamento.id;
  assert.equal((await call('/cliente/agendamentos')).data.agendamentos[0].valor_total,'35.50');
  assert.equal((await call(`/cliente/agendamentos/${appointment}/cancelar`,{})).status,200);
  assert.equal((await call('/cliente/agendamentos')).data.agendamentos[0].status,'CANCELADO');
  assert.equal((await call('/cliente/agendamentos',booking)).status,201);
  base=await boot(); // Mesmo segredo e banco; sessão sobrevive à troca de processo da aplicação.
  assert.equal((await call('/sessao')).data.usuario.perfil,'CLIENTE');
  assert.equal((await call('/cadastro',{nome:'Outro',telefone:'71922220000',senha:'SenhaCliente@2026'})).status,201);
  const {rows:[manager]}=await db.query("INSERT INTO usuario(nome,telefone,senha_hash,perfil) VALUES ('Gestor','71933330000',$1,'GESTOR') RETURNING id",[await hashPassword('SenhaGestor@2026')]);
  await call('/sair',{}); await call('/login');
  assert.equal((await call('/login',{telefone:'71933330000',senha:'SenhaGestor@2026'})).status,200);
  assert.equal((await call('/cliente/agendamentos')).status,403);
  await call('/sair',{}); await call('/login');
  assert.equal((await call('/login',{telefone:'71944440000',senha:'qualquer',acesso:'gestor-demo'})).status,401);
  base = await boot({demoGestor:true});
  assert.equal((await call('/login',{telefone:'1',senha:'qualquer',acesso:'gestor-demo'})).status,200);
  assert.equal((await call('/sessao')).data.usuario.perfil,'GESTOR');
  await call('/sair',{}); await call('/login');
  assert.equal((await call('/login',{telefone:'71911110000',senha:'errada'})).status,401);
  assert.equal((await call('/login',{telefone:'71911110000',senha:'SenhaCliente@2026'})).status,200);
  assert.equal((await call('/sessao')).data.usuario.perfil,'CLIENTE');
  await call('/sair',{}); await call('/login');
  assert.equal((await call('/login',{telefone:'2',senha:'qualquer',acesso:'gestor-demo'})).status,200);
  const response=await call('/unidades'); assert.equal(response.data.unidades.length,1); assert.ok(response.data.csrf);
  assert.equal((await call('/unidades',{nome:'Nova unidade',endereco:'Endereco',ativa:'true'})).status,200);
  assert.equal((await call('/servicos')).status,200);
  assert.equal((await call('/profissionais')).status,200);
  assert.equal((await call(`/horarios?vinculo=${link.id}`)).status,200);
  assert.equal((await call('/horarios',{vinculo:link.id,tipo:'turno',dias:['1'],inicio:'07:00',fim:'08:00'})).status,409);
  const {rows:[otherUnit]}=await db.query("INSERT INTO unidade(nome,endereco) VALUES ('Outra unidade','Rua teste 2') RETURNING id");
  const {rows:[otherLink]}=await db.query('INSERT INTO vinculo_profissional_unidade(profissional_id,unidade_id,ativo) VALUES ($1,$2,false) RETURNING id',[staff.id,otherUnit.id]);
  await db.query("INSERT INTO turno_trabalho(vinculo_id,dia_semana,hora_inicio,hora_fim) VALUES ($1,1,'10:00','11:00')",[otherLink.id]);
  assert.equal((await call(`/profissionais/${staff.id}`,{nome:'Profissional',ativo:'true',foto_url:'',unidades:[unit.id,otherUnit.id],servicos:[service.id]})).status,409);
  assert.equal((await db.query('SELECT ativo FROM vinculo_profissional_unidade WHERE id=$1',[otherLink.id])).rows[0].ativo,false);
  const {rows:[freeStaff]}=await db.query("INSERT INTO profissional(nome) VALUES ('Sem reservas') RETURNING id");
  const {rows:[freeLink]}=await db.query('INSERT INTO vinculo_profissional_unidade(profissional_id,unidade_id) VALUES ($1,$2) RETURNING id',[freeStaff.id,unit.id]);
  assert.equal((await call('/horarios',{vinculo:freeLink.id,tipo:'turno',dias:['1'],inicio:'09:00',fim:'18:00'})).status,200);
  const {rows:[freeShift]}=await db.query('SELECT id FROM turno_trabalho WHERE vinculo_id=$1',[freeLink.id]);
  assert.equal((await call('/horarios',{vinculo:freeLink.id,tipo:'turno',id:freeShift.id,dias:['1'],inicio:'08:00',fim:'17:00'})).status,200);
  assert.equal((await call('/horarios',{vinculo:freeLink.id,tipo:'pausa',turno:freeShift.id,descricao:'Almoço',inicio:'12:00',fim:'13:00'})).status,200);
  const {rows:[freePause]}=await db.query('SELECT id FROM pausa_trabalho WHERE turno_id=$1',[freeShift.id]);
  assert.equal((await call('/horarios',{vinculo:freeLink.id,tipo:'turno',id:freeShift.id,remover:'true'})).status,400);
  assert.equal((await call('/horarios',{vinculo:freeLink.id,tipo:'pausa',id:freePause.id,remover:'true'})).status,200);
  assert.equal((await call('/horarios',{vinculo:freeLink.id,tipo:'turno',id:freeShift.id,remover:'true'})).status,200);
  assert.equal((await call('/gestao/historico')).data.atendimentos.length,2);
  assert.equal((await call('/gestao/historico?inicio=2026-02-30')).status,400);
  const {rows:[past]}=await db.query("INSERT INTO agendamento(cliente_id,vinculo_id,inicio,fim,valor_total) SELECT id,$1,'2020-01-01 10:00','2020-01-01 10:30',35.50 FROM usuario WHERE telefone='71911110000' RETURNING id",[link.id]);
  await db.query("INSERT INTO item_agendamento(agendamento_id,nome,preco,duracao_minutos) VALUES ($1,'Corte',35.50,30)",[past.id]);
  assert.equal((await call(`/gestao/atendimentos/${past.id}/concluir`,{adicionais:[{nome:'Adicional',preco:'5.00'}]})).status,200);
  assert.equal((await db.query('SELECT valor_total FROM agendamento WHERE id=$1',[past.id])).rows[0].valor_total,'40.50');
  assert.equal((await call(`/gestao/atendimentos/${past.id}/concluir`,{})).status,409);
  assert.equal((await call('/auth/google')).status,503);
  assert.equal((await call('/auth/google/callback?state=x&code=x')).status,400);
  const withoutGoogle = await fetch(base+'/conta');
  assert.ok(!withoutGoogle.headers.get('content-security-policy').includes('accounts.google.com'));
  await withoutGoogle.text();
  base=await boot({google:{id:'teste.apps.googleusercontent.com',secret:'nao-e-credencial-real',redirect:'http://127.0.0.1:3000/auth/google/callback'}});
  const withGoogle = await fetch(base+'/conta', {headers:{Cookie:cookie}});
  assert.match(withGoogle.headers.get('content-security-policy'), /form-action 'self' https:\/\/accounts\.google\.com;/);
  await withGoogle.text();
  const google=await call('/auth/google'); assert.equal(google.status,200);
  const authUrl=new URL(google.data.autorizacaoUrl);
  assert.equal(authUrl.hostname,'accounts.google.com'); assert.ok(authUrl.searchParams.get('state')); assert.ok(authUrl.searchParams.get('code_challenge'));
  assert.equal((await call('/auth/google/callback?state=incorreto&code=x')).status,400);
  assert.equal((await call('/auth/google/vincular',{senha:'errada'})).status,401);
  assert.equal((await db.query('SELECT google_sub FROM usuario WHERE id=$1',[manager.id])).rows[0].google_sub,null);
});
