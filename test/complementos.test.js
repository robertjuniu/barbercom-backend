test('localização: limites, ausência, distância conhecida e antípodas', () => {
  assert.equal(coordenadas(undefined,undefined),null);
  for (const pair of [['91','0'],['0','181'],['','0'],['NaN','0'],['1e2','0'],[['1'],'2']]) assert.throws(()=>coordenadas(...pair));
  assert.deepEqual(coordenadas('0','0'),{latitude:0,longitude:0});
  assert.equal(distanciaKm({latitude:0,longitude:0},{latitude:null,longitude:null}),null);
  assert.ok(Math.abs(distanciaKm({latitude:0,longitude:0},{latitude:0,longitude:1})-111.195)<0.01);
  assert.ok(Number.isFinite(distanciaKm({latitude:0,longitude:0},{latitude:0,longitude:180})));
});

